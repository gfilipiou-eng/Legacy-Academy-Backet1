export const useTranslation = (user) => {
    // Detect language: 1. User Setting, 2. LocalStorage, 3. Browser Language, 4. English
    const browserLang = navigator.language?.split('-')[0];
    const defaultLang = TRANSLATIONS[browserLang] ? browserLang : 'en';

    const lang = localStorage.getItem('language') || user?.settings?.language || defaultLang;

    const t = (key, params = {}) => {
        let text = TRANSLATIONS[lang]?.[key] || TRANSLATIONS['en'][key] || key;
        Object.keys(params).forEach(p => {
            text = text.replace('{' + p + '}', params[p]);
        });
        return text;
    };
    return { t, lang };
};
